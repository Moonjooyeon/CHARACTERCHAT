// Build transport-size variants only. Original approved artwork is never changed.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
const root=process.cwd(),dir=path.join(root,'public/characters'),output=path.join(dir,'responsive');
await fs.mkdir(output,{recursive:true});
const manifest={};
for(const file of (await fs.readdir(dir)).filter(n=>/^character-\d+\.webp$/.test(n)).sort()){
 const source=path.join(dir,file),original=await fs.readFile(source),metadata=await sharp(original).metadata(),variants=[];
 for(const width of [96,320,640,960].filter(n=>n<metadata.width)){
  const name=file.replace('.webp',`-${width}.webp`),destination=path.join(output,name);
  const info=await sharp(original).resize({width,withoutEnlargement:true}).webp({quality:86,effort:6}).toFile(destination);
  variants.push({src:'/characters/responsive/'+name,width:info.width,height:info.height,bytes:info.size});
 }
 const after=await fs.readFile(source);if(!original.equals(after))throw Error('Original was modified: '+file);
 manifest['/characters/'+file]={width:metadata.width,height:metadata.height,bytes:original.length,sha256:crypto.createHash('sha256').update(original).digest('hex'),variants};
}
await fs.writeFile(path.join(root,'app/lib/portrait-variants.ts'),'// Generated by scripts/build-portrait-variants.mjs; original artwork is unchanged.\nexport const portraitVariants = '+JSON.stringify(manifest,null,2)+' as const;\n');
const items=Object.values(manifest);console.log(JSON.stringify({originals:items.length,originalBytes:items.reduce((s,x)=>s+x.bytes,0),variantCount:items.reduce((s,x)=>s+x.variants.length,0),variantBytes:items.reduce((s,x)=>s+x.variants.reduce((t,v)=>t+v.bytes,0),0)},null,2));
